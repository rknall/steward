/*
 * Scenario store for the adventures module.
 *
 * A scenario describes a TSO scenario adventure as a list of trips: what to
 * produce and which grids to apply it to. One JSON file per scenario; the
 * file base name is the id. File format (version 1):
 *   { "version": 1, "label": str, "adventure": str,
 *     "trips": [ { "items": [ { "buff": str, "grids": [int>0, ...],
 *                               "amount": int>0 (optional),
 *                               "quest": str (optional) } ] } ] }
 * A trip without items (or {}) is a visit only. Unknown keys are ignored and
 * buff names are the full game names.
 *
 * Two sources feed one list. Built-in scenarios ship in the bundle as
 * S.modules.adventures.builtinScenarios = { id: text } (generated by the
 * build from the repo's scenarios/ folder). A user file
 * <steward folder>/adventures/scenarios/<id>.json replaces the built-in of the
 * same id, so a player can correct a file without a new build. Both go
 * through the one parser, fromText().
 *
 * A text that cannot be parsed is listed as a broken entry { id, path, error }
 * instead of being skipped, so the user sees it. A broken user file replaces
 * the built-in of its id for the same reason.
 *
 * Amounts: `amount` is the item's total need over its grids for the trip (a
 * wiki total such as 10 boulders over four grids); without it the total is one
 * per grid. Each grid is a group that takes only what it needs, so a send
 * offers at most `amount` and what the grid does not take stays in stock.
 *
 * Quest: `quest` is the full quest name. When it is set, only that quest can
 * make the item wanted for Apply; production ignores it.
 *
 * Bundle slot: module file; top level only assigns
 * S.modules.adventures.scenarios; templates and the built-in table are read
 * at call time.
 */

(function (S) {

    if (!S.modules.adventures) S.modules.adventures = {};

    var SUBDIR = 'adventures/scenarios';
    var FORMAT_VERSION = 1;
    var warnedFolder = false;

    function isArray(v) {
        return Object.prototype.toString.call(v) === '[object Array]';
    }

    function isPlainObject(v) {
        return v !== null && typeof v === 'object' && Object.prototype.toString.call(v) === '[object Object]';
    }

    function str(v) {
        return typeof v === 'string' ? v : '';
    }

    function trim(v) {
        return str(v).replace(/^\s+|\s+$/g, '');
    }

    function posInt(v) {
        return typeof v === 'number' && isFinite(v) && Math.floor(v) === v && v > 0;
    }

    function templates() {
        return S.modules.adventures.templates;
    }

    // ---- Parsing ----------------------------------------------------------

    // Pure. The normalised copy of an item, or a reason string.
    function normItem(v, where) {
        if (!isPlainObject(v)) return where + ' is not an object';
        if (typeof v.buff !== 'string' || trim(v.buff) === '') return where + ' has no buff name';
        if (!isArray(v.grids) || v.grids.length === 0) return where + ' has no grids';
        var grids = [];
        for (var g = 0; g < v.grids.length; g++) {
            if (!posInt(v.grids[g])) return where + ' has a bad grid (' + String(v.grids[g]) + ')';
            grids.push(v.grids[g]);
        }
        var amount = null;
        if (v.amount !== undefined && v.amount !== null) {
            if (!posInt(v.amount)) return where + ' has a bad amount (' + String(v.amount) + ')';
            amount = v.amount;
        }
        var quest = null;
        if (v.quest !== undefined && v.quest !== null) {
            if (typeof v.quest !== 'string' || trim(v.quest) === '') return where + ' has a bad quest';
            quest = trim(v.quest);
        }
        return { buff: v.buff, grids: grids, amount: amount, quest: quest };
    }

    // Pure. { trips } or { error }: at least one trip, each { items: [...] }
    // with a missing items list meaning a visit only.
    function parseTrips(v) {
        if (!isArray(v) || v.length === 0) return { error: 'no trips' };
        var out = [];
        for (var i = 0; i < v.length; i++) {
            var t = v[i];
            var where = 'trip ' + (i + 1);
            if (!isPlainObject(t)) return { error: where + ' is not an object' };
            var items = [];
            if (t.items !== undefined && t.items !== null) {
                if (!isArray(t.items)) return { error: where + ' items is not a list' };
                for (var j = 0; j < t.items.length; j++) {
                    var it = normItem(t.items[j], where + ' item ' + (j + 1));
                    if (typeof it === 'string') return { error: it };
                    items.push(it);
                }
            }
            out.push({ items: items });
        }
        return { trips: out };
    }

    // Pure. The normalised trips, or null on any violation.
    function normTrips(v) {
        var r = parseTrips(v);
        return r.trips || null;
    }

    function broken(id, path, error) {
        return { id: id, path: path, error: error };
    }

    // Pure. `source` is 'builtin' or 'file'; the id always comes from the
    // caller (the file name or the built-in key), never from the text.
    function fromText(id, path, text, source) {
        var data;
        try {
            data = JSON.parse(text);
        } catch (e) {
            return broken(id, path, 'not valid JSON: ' + e);
        }
        if (!isPlainObject(data)) return broken(id, path, 'not a scenario: top level is not an object');
        if (data.version !== FORMAT_VERSION) {
            return broken(id, path, 'unsupported version ' + String(data.version) + ' (expected ' + FORMAT_VERSION + ')');
        }
        var label = trim(data.label);
        if (label === '') return broken(id, path, 'label is empty');
        var adventure = str(data.adventure);
        if (adventure === '') return broken(id, path, 'adventure is empty');
        var tr = parseTrips(data.trips);
        if (tr.error) return broken(id, path, tr.error);
        return {
            id:        id,
            label:     label,
            adventure: adventure,
            trips:     tr.trips,
            source:    source === 'file' ? 'file' : 'builtin',
            path:      path
        };
    }

    // ---- Records ----------------------------------------------------------

    function compareIds(a, b) {
        return a.id < b.id ? -1 : (a.id > b.id ? 1 : 0);
    }

    // Built-in table entries as records, in key order. Ids that are not valid
    // file ids are skipped, since a user file could never override them.
    function builtins() {
        var table = S.modules.adventures.builtinScenarios;
        var out = {};
        if (!isPlainObject(table)) return out;
        for (var id in table) {
            if (!Object.prototype.hasOwnProperty.call(table, id)) continue;
            if (!templates().validId(id)) {
                S.kernel.warn('adventures', 'built-in scenario id', id, 'is not a valid file name: skipped');
                continue;
            }
            out[id] = fromText(id, 'built-in', str(table[id]), 'builtin');
        }
        return out;
    }

    // Records sorted by label (case-insensitive), then broken entries by id.
    function list() {
        var byId = builtins();
        var es = templates().entriesIn(SUBDIR);
        if (es === null) {
            if (!warnedFolder) {
                warnedFolder = true;
                S.kernel.warn('adventures', 'no writable steward folder: only built-in scenarios are listed');
            }
        } else {
            for (var i = 0; i < es.length; i++) {
                var r = S.kernel.files.readText(es[i].path);
                byId[es[i].id] = r.ok
                    ? fromText(es[i].id, es[i].path, r.text, 'file')
                    : broken(es[i].id, es[i].path, r.message);
            }
        }
        var recs = [];
        var bad = [];
        for (var id in byId) {
            if (!Object.prototype.hasOwnProperty.call(byId, id)) continue;
            if (byId[id].error !== undefined) bad.push(byId[id]);
            else recs.push(byId[id]);
        }
        recs.sort(function (a, b) {
            var x = a.label.toLowerCase(), y = b.label.toLowerCase();
            if (x !== y) return x < y ? -1 : 1;
            return compareIds(a, b);
        });
        bad.sort(compareIds);
        return recs.concat(bad);
    }

    // The record, or null when the id is missing or broken.
    function get(id) {
        var all = list();
        for (var i = 0; i < all.length; i++) {
            if (all[i].id === id) return all[i].error !== undefined ? null : all[i];
        }
        return null;
    }

    // ---- Amounts ----------------------------------------------------------

    // Pure. Unique buff names in trip order.
    function buffsOf(rec) {
        var out = [];
        var trips = rec && rec.trips ? rec.trips : [];
        for (var i = 0; i < trips.length; i++) {
            for (var j = 0; j < trips[i].items.length; j++) {
                var b = trips[i].items[j].buff;
                if (out.indexOf(b) === -1) out.push(b);
            }
        }
        return out;
    }

    // Pure. What one send offers at most: the item's trip total, or 1. The
    // grid takes only its group's share and the rest stays in stock.
    function sendAmount(item) {
        return item.amount !== null ? item.amount : 1;
    }

    // Pure. How many of the item the trip needs while grids are open: the
    // trip total when given, else one per open grid. Produced in one go at
    // home so no extra home trip is needed (the stock-out return stays a
    // fallback).
    function needOf(item, openGrids) {
        if (!(openGrids > 0)) return 0;
        return item.amount !== null ? item.amount : openGrids;
    }

    // Pure. { buff: need } summed over the trip's items; isOpen(item, grid)
    // says whether a grid still waits.
    function tripNeeds(trip, isOpen) {
        var out = {};
        var items = trip && trip.items ? trip.items : [];
        for (var i = 0; i < items.length; i++) {
            var open = 0;
            for (var g = 0; g < items[i].grids.length; g++) {
                if (isOpen(items[i], items[i].grids[g])) open++;
            }
            var need = needOf(items[i], open);
            if (need > 0) out[items[i].buff] = (out[items[i].buff] || 0) + need;
        }
        return out;
    }

    S.modules.adventures.scenarios = {
        SUBDIR:         SUBDIR,
        FORMAT_VERSION: FORMAT_VERSION,
        normTrips:      normTrips,
        fromText:       fromText,
        list:           list,
        get:            get,
        buffsOf:        buffsOf,
        sendAmount:     sendAmount,
        needOf:         needOf,
        tripNeeds:      tripNeeds
    };

}(Steward));
